#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int		res;
	int		sign;
	size_t	i;

	i = 0;
	res = 0;
	sign = 1;
	while (nptr[i] == ' ' || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i] == '-')
			sign = -1;
		i++;
	}
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		res = nptr[i] - '0' + res * 10;
		i++;
	}
	return (res * sign);
}
